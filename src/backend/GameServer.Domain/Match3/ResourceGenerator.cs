namespace GameServer.Domain.Match3;

/// <summary>
/// The resources one committed Swap's cleared Gems generated
/// (<c>COMBAT_RULES.md</c> §2, <c>GAME_RULES.md</c> §17 step 12).
///
/// <code>
/// ResourceGeneration
/// ├── BaseDamagePool     ATK Gems    +10 each   (COMBAT_RULES.md §2)
/// ├── DefensePool        DEF Gems    +5  each
/// ├── HealPool           HP Gems     +20 each
/// └── Power              POWER Gems  +10 each
/// </code>
///
/// <b>There is no match-tier multiplier (OD-3).</b> Every uniquely matched Gem
/// contributes its type's `BaseOutput` once, whatever shape consumed it: a
/// Match 3, a Match 4, a Match 5, and an L/T shape all contribute at the same
/// per-Gem rate (<c>COMBAT_RULES.md</c> §2 item 6). A larger Match earns more
/// only because it consumes more cells.
///
/// <b>This is Transient Resolution State</b> (<c>GAME_STATE.md</c> §3): it exists
/// only for the duration of resolving one Swap and is consumed by the downstream
/// resolution steps of the same resolution (13–17). It is <b>not</b> a
/// <c>BattleState</c> or <c>PetState</c> field, it is never serialized, never
/// written to Redis, and never delivered on the wire.
///
/// <b>Three of its four members are transient by design, not by omission.</b>
/// Only <c>Power</c> has a documented persistent home — the active Pet's
/// <c>PetState.Power</c>
/// (<c>GAME_STATE.md</c> §2.3, <c>COMBAT_RULES.md</c> §1.1, <c>ADR-011</c>
/// item 5) — so this stage writes
/// its <see cref="Power"/> into that state and leaves the other three here.
/// <c>COMBAT_RULES.md</c> §3 step 1's "ATK-Gem-generated damage pool <b>for this
/// action</b>" is scoped to one action by its own wording, and Defense is read
/// per damage instance by §3.2's mitigation formula; neither is a persistent
/// stat. Adding them to <c>PetState</c> would extend a closed field list
/// (<c>GAME_STATE.md</c> §2.3) that no rule asks this stage to extend.
///
/// <b>Defense now feeds a temporary stat buff, not a Shield pool (TASK-299).</b>
/// <c>COMBAT_RULES.md</c> §2 and §5.4.6/§5.5.6 make a DEF-Gem match grant the
/// acting actor a Turn-based <c>BuffDebuff</c> with <c>TargetStat = "DEF"</c>
/// whose magnitude is this action's <see cref="DefensePool"/>, so the pool is
/// still transient here and the persistent carrier is the existing
/// <c>StatusEffects[]</c> instance — not a new state member. The pool is never
/// converted into a Shield and no absorption pool exists for DEF Gems.
///
/// <b>The pools accumulate across every pass of the Swap</b>
/// (<c>MATCH3_RULES.md</c> §5.7 item 7): each pass's unique cleared cells generate
/// once, at the same per-Gem rate, and the Swap's total is the sum. No "cascade
/// bonus" multiplier exists in MVP.
/// </summary>
/// <param name="BaseDamagePool">
/// The ATK-Gem damage generated by this Swap, in absolute damage points. It feeds
/// the Damage Pipeline's Base Damage step for this action
/// (<c>COMBAT_RULES.md</c> §3 step 1). It is <b>not</b> <c>PetState.ATK</c>,
/// which is the persistent attack stat of §1.1 — this is the transient output the
/// ATK Gems contributed on top of it.
/// </param>
/// <param name="DefensePool">
/// The Defense generated by this Swap's DEF Gems. It is separate from
/// <c>PetState.DEF</c>, the persistent base stat the mitigation formula reads
/// (<c>COMBAT_RULES.md</c> §3.2); this pool is what the DEF Gems contributed, and
/// it is applied as the magnitude of the acting actor's temporary
/// <c>TargetStat = "DEF"</c> buff (<c>COMBAT_RULES.md</c> §5.4.6 / §5.5.6,
/// TASK-299). It no longer becomes a Shield absorption pool.
/// </param>
/// <param name="HealPool">
/// The healing generated by this Swap's HP Gems, consumed by the player-effects
/// step (<c>COMBAT_RULES.md</c> §4).
/// </param>
/// <param name="Power">
/// The Power generated by this Swap's POWER Gems, before the 0–100 clamp
/// (<c>COMBAT_RULES.md</c> §2, <c>GAME_RULES.md</c> §12). The clamp belongs to
/// the persistent write, and is applied by
/// <see cref="ResourceGenerator.ApplyPower"/> so the delta reported in
/// <c>PowerChanged</c> remains the clamped one.
/// </param>
/// <param name="ClearedGemCounts">
/// How many cells of each Gem type this Swap cleared, over the union of every
/// pass's cleared cells (<c>MATCH3_RULES.md</c> §5.8.2). This is the accumulation
/// the pools above are computed from, surfaced so a caller or a test can read
/// what was cleared without re-deriving it from the pools.
/// </param>
public readonly record struct ResourceGeneration(
    int BaseDamagePool,
    int DefensePool,
    int HealPool,
    int Power,
    ClearedGemCounts ClearedGemCounts)
{
    /// <summary>
    /// The generation of a Swap that cleared nothing — every pool at zero
    /// (<c>MATCH3_RULES.md</c> §4.3 item 4).
    /// </summary>
    public static ResourceGeneration None => new(0, 0, 0, 0, ClearedGemCounts.None);

    /// <summary>True when no resource of any kind was generated.</summary>
    public bool IsEmpty =>
        BaseDamagePool == 0 && DefensePool == 0 && HealPool == 0 && Power == 0;
}

/// <summary>
/// The number of cleared cells of each Gem type
/// (<c>MATCH3_RULES.md</c> §1.1, §5.8.2 item 5).
///
/// A cleared cell is counted once however many shapes or effects named it:
/// accounting is by the <b>union</b> of a pass's cleared cells, never the sum of
/// the effects' sizes (<c>MATCH3_RULES.md</c> §5.8.2 items 1–2, 5).
/// </summary>
/// <param name="Atk">Cleared ATK Gems.</param>
/// <param name="Def">Cleared DEF Gems.</param>
/// <param name="Hp">Cleared HP Gems.</param>
/// <param name="Power">Cleared POWER Gems.</param>
public readonly record struct ClearedGemCounts(int Atk, int Def, int Hp, int Power)
{
    /// <summary>No cleared cells.</summary>
    public static ClearedGemCounts None => new(0, 0, 0, 0);

    /// <summary>The total number of cleared cells across all four types.</summary>
    public int Total => Atk + Def + Hp + Power;

    /// <summary>The count for one Gem type.</summary>
    public int For(GemType type) => type switch
    {
        GemType.Atk => Atk,
        GemType.Def => Def,
        GemType.Hp => Hp,
        GemType.Power => Power,
        _ => throw new ArgumentOutOfRangeException(nameof(type), type, "Not a documented Gem type."),
    };

    /// <summary>This count with one cell of <paramref name="type"/> added.</summary>
    public ClearedGemCounts Increment(GemType type) => type switch
    {
        GemType.Atk => this with { Atk = Atk + 1 },
        GemType.Def => this with { Def = Def + 1 },
        GemType.Hp => this with { Hp = Hp + 1 },
        GemType.Power => this with { Power = Power + 1 },
        _ => throw new ArgumentOutOfRangeException(nameof(type), type, "Not a documented Gem type."),
    };
}

/// <summary>
/// Resource Generation — <c>GAME_RULES.md</c> §17 step 12, the conversion of a
/// committed Swap's cleared Gems into the documented resource pools
/// (<c>COMBAT_RULES.md</c> §2).
///
/// <code>
/// Swap → Match Detection → Cascade Resolution → Cleared Gems
///                                             → Resource Generation → PetState
/// </code>
///
/// <b>Its persistent outputs are written by this type.</b> Two of the four
/// generated pools have a documented persistent home on the active Pet's
/// <c>PetState</c> (the combat-stat home <c>GAME_STATE.md</c> §2.3 and
/// <c>ADR-011</c> item 5 designate), and
/// each is written by the one method that owns it: <c>Power</c> by
/// <see cref="ApplyPower"/> (<c>GAME_RULES.md</c> §17 steps 12–13) and the
/// HealPool by <see cref="ApplyHeal"/> (§17 step 14, <c>COMBAT_RULES.md</c> §4
/// item 1). Base Damage Pool and Defense Pool deliberately reach no state —
/// <c>COMBAT_RULES.md</c> §3's Damage Pipeline, which consumes them, is a separate
/// stage.
///
/// <b>Rates.</b> The per-Gem base outputs are <c>COMBAT_RULES.md</c> §2's table:
///
/// <code>
/// ATK Gem    +10 Base Damage
/// DEF Gem    +5  Defense pool
/// HP Gem     +20 Heal pool
/// POWER Gem  +10 Power
/// </code>
///
/// <b>Contribution.</b> For one committed action,
/// <c>Contribution(type) = BaseOutput(type) × count(type)</c>, where
/// <c>count(type)</c> is the number of unique matched cells of that Gem type
/// (<c>COMBAT_RULES.md</c> §2 item 6, <c>MATCH3_RULES.md</c> §5.7 items 1–8).
/// <b>There is no match-tier multiplier (OD-3):</b> Match 3, Match 4, Match 5,
/// and L/T shapes all contribute at the same per-Gem rate, and the product is an
/// exact integer with no division and no rounding.
///
/// <b>Which cells generate, and how often.</b> Owned by <c>MATCH3_RULES.md</c>
/// §5.7 and §3.3: once per unique cell of a pass, over that pass's union, and the
/// action's total is the sum over its passes. A cell shared by two shapes of one
/// pass generates once; a later pass's matched cells are new cells and accumulate
/// (<c>§5.7 items 2 and 7</c>). Overlapping shapes therefore produce no double
/// resources, and a Cascade is not a multiplier.
///
/// <b>Determinism.</b> This conversion is a pure function of the cleared cells:
/// it draws no RNG, reads no wall clock, and depends on no enumeration order
/// (<c>MATCH3_RULES.md</c> §7.2, <c>AGENTS.md</c> §11). The same resolution
/// always produces the same pools.
/// </summary>
public static class ResourceGenerator
{
    /// <summary>
    /// The documented per-Gem base output of a Gem type
    /// (<c>COMBAT_RULES.md</c> §2).
    /// </summary>
    /// <param name="type">The Gem type of one consumed cell.</param>
    /// <returns>The base output in the pool that Gem type feeds.</returns>
    public static int BaseOutputFor(GemType type) => type switch
    {
        GemType.Atk => AtkGemBaseDamage,
        GemType.Def => DefGemBaseDefense,
        GemType.Hp => HpGemBaseHeal,
        GemType.Power => PowerGemBasePower,
        _ => throw new ArgumentOutOfRangeException(nameof(type), type, "Not a documented Gem type."),
    };

    /// <summary>
    /// <c>ATK Gem → +10 Base Damage</c> (<c>COMBAT_RULES.md</c> §2).
    /// </summary>
    public const int AtkGemBaseDamage = 10;

    /// <summary>
    /// <c>DEF Gem → +5 Defense pool</c> (<c>COMBAT_RULES.md</c> §2).
    ///
    /// It is the per-Gem rate of the DEF-Gem buff's magnitude: a committed
    /// action's <see cref="ResourceGeneration.DefensePool"/> is
    /// <c>DefGemBaseDefense × count(DEF)</c> and becomes the temporary
    /// <c>TargetStat = "DEF"</c> instance's <c>Magnitude</c>
    /// (<c>COMBAT_RULES.md</c> §5.4.6; TASK-299). The rate is unchanged — only the
    /// effect's kind changed.
    /// </summary>
    public const int DefGemBaseDefense = 5;

    /// <summary>
    /// The Pet DEF buff's duration in Turns — the Pet row of
    /// <c>COMBAT_RULES.md</c> §5.4.6's window table.
    ///
    /// The Player's DEF match applies the buff at step 12/14 of a Turn, the Boss
    /// attacks in the same Turn's step 18, and step 19a consumes and removes the
    /// instance: one Turn is exactly the one opponent attack phase the buff
    /// covers.
    /// </summary>
    public const int PlayerDefBuffDurationTurns = 1;

    /// <summary>
    /// The Boss DEF buff's duration in Turns — the Boss row of
    /// <c>COMBAT_RULES.md</c> §5.4.6's window table.
    ///
    /// The Boss's DEF match applies the buff at step 18a, which is after the
    /// Player's step-15 attack of that Turn, so the buff must survive that Turn's
    /// step 19a (2 → 1) to cover the Player's step-15 attack of the following
    /// Turn, and is consumed and removed at that Turn's step 19a (1 → 0). The
    /// value differs from the Pet's only because the Player acts before the Boss
    /// inside one atomic Round; both express the same "one opponent attack phase"
    /// window.
    /// </summary>
    public const int BossDefBuffDurationTurns = 2;

    /// <summary>
    /// <c>HP Gem → +20 Heal pool</c> (<c>COMBAT_RULES.md</c> §2).
    /// </summary>
    public const int HpGemBaseHeal = 20;

    /// <summary>
    /// <c>POWER Gem → +10 Power</c> (<c>COMBAT_RULES.md</c> §2).
    /// </summary>
    public const int PowerGemBasePower = 10;

    /// <summary>
    /// The documented Power range's ceiling (<c>GAME_RULES.md</c> §12:
    /// "Range: 0–100"; <c>COMBAT_RULES.md</c> §1.1).
    ///
    /// §12 states Power "must never exceed the configured maximum unless an
    /// explicit future mechanic allows it". No such mechanic exists, so the write
    /// of a generated Power value is capped here.
    /// </summary>
    public const int MaxPower = 100;

    /// <summary>
    /// The documented Power range's floor (<c>GAME_RULES.md</c> §12).
    ///
    /// Generation never decreases Power, so this floor is not reached by this
    /// stage; it is applied by <see cref="ApplyPower"/> so that the one operation
    /// that writes the persistent value enforces the whole documented range
    /// rather than half of it.
    /// </summary>
    public const int MinPower = 0;

    /// <summary>
    /// Generates the resources of one committed Swap from its resolved passes
    /// (<c>GAME_RULES.md</c> §17 step 12, <c>COMBAT_RULES.md</c> §2).
    ///
    /// <code>
    /// for each pass, in the resolution's own order          MATCH3_RULES.md §4.2
    ///     a cell cleared twice in the pass → counted once   §3.3 item 3
    ///     pools += BaseOutput(cell's Gem type)               §2 item 6
    /// </code>
    ///
    /// <b>Union, not per-effect sums.</b> A pass's cleared cells are its unique
    /// cleared cells, each once (<c>MATCH3_RULES.md</c> §3.3 item 3, §5.7 item 2):
    /// a cell shared by an L/T's arms, or named by more than one shape, generates
    /// once. The pools are therefore computed over the union and never by adding
    /// up per-shape totals.
    ///
    /// <b>No match-tier multiplier.</b> Each cell contributes its type's
    /// <c>BaseOutput</c> once, whatever shape consumed it
    /// (<c>COMBAT_RULES.md</c> §2 item 6, OD-3): a Match 4 is four cells' worth,
    /// a Match 5 is five cells' worth, and an L/T is one contribution per unique
    /// cell. No division, rounding, or precision case exists.
    ///
    /// <b>Passes accumulate.</b> The action's total is the sum over its passes
    /// (<c>MATCH3_RULES.md</c> §5.7 item 7). A Cascade is not a multiplier: each
    /// newly confirmed cascade Match contributes again, under the same per-cell
    /// rule.
    /// </summary>
    /// <param name="resolution">
    /// The committed Swap's resolution, whose passes carry their unique cleared
    /// cells with the Gem type each held when it was cleared
    /// (<c>MATCH3_RULES.md</c> §3.3 item 3).
    /// </param>
    /// <returns>
    /// The Swap's generated pools and the cleared-cell counts they were computed
    /// from. A resolution with no passes generates nothing.
    /// </returns>
    public static ResourceGeneration Generate(CascadeResolver.CascadeResult resolution)
    {
        var counts = ClearedGemCounts.None;
        var baseDamage = 0;
        var defense = 0;
        var heal = 0;
        var power = 0;

        foreach (var pass in resolution.Passes)
        {
            // §3.3 item 3: one entry per unique cleared cell of the pass, ascending
            // index, carrying the cell's type.
            foreach (var cell in pass.ClearedGems)
            {
                // COMBAT_RULES.md §2 item 6 / OD-3–OD-4: BaseOutput × count, with no
                // match-tier factor and no division. A cell contributes exactly its
                // type's base output.
                var generated = BaseOutputFor(cell.GemType);

                switch (cell.GemType)
                {
                    case GemType.Atk:
                        baseDamage += generated;
                        break;
                    case GemType.Def:
                        defense += generated;
                        break;
                    case GemType.Hp:
                        heal += generated;
                        break;
                    case GemType.Power:
                        power += generated;
                        break;
                    default:
                        throw new ArgumentOutOfRangeException(
                            nameof(resolution), cell.GemType, "Not a documented Gem type.");
                }

                counts = counts.Increment(cell.GemType);
            }
        }

        return new ResourceGeneration(baseDamage, defense, heal, power, counts);
    }

    /// <summary>
    /// Writes generated Power into the active Pet's persistent state, clamped to
    /// the documented 0–100 range (<c>COMBAT_RULES.md</c> §2, <c>GAME_RULES.md</c>
    /// §12).
    ///
    /// <code>
    /// new Power = clamp(previous Power + generated Power, 0, 100)
    /// </code>
    ///
    /// Only <c>Power</c> changes. The other <c>PetState</c> fields — the other
    /// combat stats, the Element, the Passive identity and progress, and the
    /// Match/Combo values this stage does not own, which live at the
    /// <c>BattleState</c> root — are carried across unchanged by the <c>with</c>
    /// expression.
    ///
    /// The clamp is applied here, at the single point the persistent value is
    /// written, rather than to the transient <see cref="ResourceGeneration.Power"/>:
    /// the pool stays the amount the Swap generated, while the state holds the
    /// amount in force. A gain that the cap absorbs is visible as a delta of less
    /// than the pool.
    /// </summary>
    /// <param name="previous">The active Pet's state before this Swap's generation.</param>
    /// <param name="generation">The Swap's generated resources.</param>
    /// <returns>
    /// The state this stage leaves: <paramref name="previous"/> with its
    /// <c>Power</c> incremented by the generated amount and clamped to 0–100.
    /// </returns>
    public static Battle.PetState ApplyPower(
        Battle.PetState previous,
        int powerDelta)
    {
        var updated = previous.Power + powerDelta;

        if (updated > MaxPower)
        {
            updated = MaxPower;
        }
        else if (updated < MinPower)
        {
            updated = MinPower;
        }

        return previous with { Power = updated };
    }

    public static Battle.PetState ApplyPower(
        Battle.PetState previous,
        ResourceGeneration generation) =>
        ApplyPower(previous, generation.Power);

    /// <summary>
    /// Writes generated Power into the Boss's persistent state, clamped to
    /// the documented 0–100 range (<c>COMBAT_RULES.md</c> §2, <c>BOSS_RULES.md</c> §4.1, <c>ADR-029</c>).
    ///
    /// <code>
    /// new Power = clamp(previous Power + generated Power, 0, 100)
    /// </code>
    ///
    /// The Boss-side counterpart of <see cref="ApplyPower(Battle.PetState, int)"/>:
    /// same rate table (+10 Power per uniquely matched POWER cell, U-1 Option A),
    /// same 0–100 clamp, but writing <see cref="Battle.BossState.Power"/> rather than
    /// <see cref="Battle.PetState.Power"/>.
    /// </summary>
    /// <param name="previous">The Boss's state before this match generation.</param>
    /// <param name="powerDelta">The generated Power amount.</param>
    /// <returns>
    /// <paramref name="previous"/> with its <c>Power</c> incremented by the generated
    /// amount and clamped to 0–100.
    /// </returns>
    public static Battle.BossState ApplyBossPower(
        Battle.BossState previous,
        int powerDelta)
    {
        var updated = previous.Power + powerDelta;

        if (updated > MaxPower)
        {
            updated = MaxPower;
        }
        else if (updated < MinPower)
        {
            updated = MinPower;
        }

        return previous with { Power = updated };
    }

    public static Battle.BossState ApplyBossPower(
        Battle.BossState previous,
        ResourceGeneration generation) =>
        ApplyBossPower(previous, generation.Power);

    /// <summary>
    /// Resolves the player effects of one committed Swap: applies the HealPool the
    /// original HP Gems generated to the active Pet's persistent HP
    /// (<c>GAME_RULES.md</c> §17 step 14, <c>COMBAT_RULES.md</c> §4 item 1).
    ///
    /// <code>
    /// new HP = min(previous HP + generation.HealPool, MaxHP)
    /// </code>
    ///
    /// <b>The ceiling is MaxHP, and overheal is discarded.</b> §4 item 1: "Heal
    /// effects restore HP up to Max HP; overheal is discarded unless a Relic
    /// explicitly grants overheal/temp-HP." No Relic grants it in MVP (§4 item 4
    /// notes Heal modifiers exist but none is implemented), so the clamp is the
    /// whole of the rule and the discarded excess is stored nowhere: it is not
    /// carried into a later Swap, and it is not written to any other field.
    ///
    /// <b>HP has no documented floor applied here.</b> §4 item 1 bounds healing
    /// from above only, and this step only ever <i>adds</i> a non-negative pool, so
    /// HP can never be driven below the value the Damage Pipeline left it at
    /// (<c>COMBAT_RULES.md</c> §3 owns damage, which is not this stage). A
    /// <c>HealPool</c> of <c>0</c> — the ordinary case of a Swap that cleared no HP
    /// Gem — therefore leaves HP exactly unchanged, whatever it was.
    ///
    /// <b>No event.</b> Healing is a state-only change: <c>GAME_EVENTS.md</c> §2 has
    /// no heal event, so this step emits nothing and adds no
    /// <c>BattleEventType</c> member. The new HP is delivered, if at all, as state
    /// — adding it to the wire is a protocol change owned by its own task
    /// (<c>SIGNALR_PROTOCOL.md</c> §4.3 item 2).
    ///
    /// <b>No RNG and no second input.</b> The write is a pure function of the
    /// previous state and the pool the resolution already generated: it draws
    /// nothing, reads no clock, and re-derives nothing from the board
    /// (<c>MATCH3_RULES.md</c> §7.2, <c>AGENTS.md</c> §11). The pool is <b>not</b>
    /// scaled again here — each consumed Gem's <c>BaseOutput</c> was added once,
    /// with no match-tier factor, when the pool was generated
    /// (<c>COMBAT_RULES.md</c> §2 item 6).
    ///
    /// <b>The pool is transient and stays on the resolution.</b> Reading it here
    /// does not move it: <c>HealPool</c> remains Transient Resolution State
    /// (<c>GAME_STATE.md</c> §3) on <c>SwapExecutionResult.Resources</c>, and is not
    /// added to <c>PetState</c> or <c>BattleState</c>.
    ///
    /// <b>Only HP changes.</b> Every other <c>PetState</c> field — including
    /// <c>Power</c>, which <see cref="ApplyPower"/> owns, and the Match/Combo
    /// values the accounting owns — is carried across unchanged by the <c>with</c>
    /// expression.
    /// </summary>
    /// <param name="previous">
    /// The active Pet's state before this Swap's healing — the source of the
    /// current
    /// <c>HP</c>, of the <c>MaxHP</c> that bounds it, and of every field this step
    /// does not own.
    /// </param>
    /// <param name="generation">
    /// The Swap's generated resources, whose <see cref="ResourceGeneration.HealPool"/>
    /// is the healing to apply.
    /// </param>
    /// <returns>
    /// The state this step leaves: <paramref name="previous"/> with its <c>HP</c>
    /// increased by the HealPool and clamped to <c>MaxHP</c>.
    /// </returns>
    public static Battle.PetState ApplyHeal(
        Battle.PetState previous,
        int rawHeal,
        IReadOnlyList<Battle.StatusEffect>? bossStatusEffects = null) =>
        Combat.HealResolution.ApplyPetHeal(previous, rawHeal, bossStatusEffects);

    public static Battle.PetState ApplyHeal(
        Battle.PetState previous,
        ResourceGeneration generation,
        IReadOnlyList<Battle.StatusEffect>? bossStatusEffects = null) =>
        ApplyHeal(previous, generation.HealPool, bossStatusEffects);

    /// <summary>
    /// Applies HP-gem healing to Boss HP, clamped to MaxHP (<c>ADR-026</c> D2, <c>COMBAT_RULES.md</c> §4 item 1).
    /// </summary>
    public static Battle.BossState ApplyBossHeal(
        Battle.BossState previous,
        int rawHeal) =>
        Combat.HealResolution.ApplyBossHeal(previous, rawHeal);

    public static Battle.BossState ApplyBossHeal(
        Battle.BossState previous,
        ResourceGeneration generation) =>
        ApplyBossHeal(previous, generation.HealPool);

    /// <summary>
    /// Applies this action's DEF-Gem buff to the active Pet
    /// (<c>COMBAT_RULES.md</c> §2, §5.4.6; TASK-299).
    ///
    /// <code>
    /// PetState.ActiveStatusEffects +=
    ///     StatusEffect("DefenseBuff", BuffDebuff, source: Player,
    ///                  Magnitude: defensePool, RemainingTurns: 1, TargetStat: "DEF")
    /// </code>
    ///
    /// <b>One instance, refreshed — never stacked.</b>
    /// <c>COMBAT_RULES.md</c> §5.4.6's stacking statement is §5.2 item 2's MVP
    /// default: a later DEF-Gem resolution refreshes the active
    /// <c>"DefenseBuff"</c> instance — the magnitude is <b>set</b> to the newest
    /// application and its duration reset (<c>StatusEffectLifecycle.Apply</c>,
    /// <c>GAME_STATE.md</c> §5.1.1 item 1) — and magnitudes are never summed. The
    /// caller passes one action's whole pool, so several DEF matches inside one
    /// action still produce exactly one instance.
    ///
    /// <b>A zero pool applies nothing.</b> An action that cleared no DEF Gem has
    /// no buff to grant, and an absent instance is how "no buff is active" is
    /// spelled (<c>GAME_STATE.md</c> §2.3.1 item 8) — it must not create a
    /// zero-magnitude instance.
    ///
    /// <b>The duration is the Pet row of §5.4.6's window table.</b> The buff is
    /// active through this same Round's Boss attack (step 18) and is consumed and
    /// removed at that Turn's step 19a, so one Turn of duration is exactly one
    /// covered opponent attack phase.
    /// </summary>
    /// <param name="previous">The active Pet's state before this Swap's DEF buff.</param>
    /// <param name="defensePool">This action's generated Defense.</param>
    /// <returns>
    /// <paramref name="previous"/> with the buff applied or refreshed, and every
    /// other member carried across unchanged.
    /// </returns>
    public static Battle.PetState ApplyDefenseBuff(
        Battle.PetState previous,
        int defensePool)
    {
        if (defensePool <= 0)
        {
            return previous;
        }

        var buff = Battle.StatusEffect.TurnBased(
            Battle.StatusEffectLifecycle.DefenseBuffId,
            Battle.StatusEffectType.BuffDebuff,
            Battle.StatusEffectSource.Player,
            defensePool,
            PlayerDefBuffDurationTurns,
            Battle.StatusEffectLifecycle.DefenseStat);

        return previous with
        {
            ActiveStatusEffects = Battle.StatusEffectLifecycle.Apply(previous.ActiveStatusEffects, buff),
        };
    }

    public static Battle.PetState ApplyDefenseBuff(
        Battle.PetState previous,
        ResourceGeneration generation) =>
        ApplyDefenseBuff(previous, generation.DefensePool);

    /// <summary>
    /// Applies this action's DEF-Gem buff to the Boss
    /// (<c>COMBAT_RULES.md</c> §2, §5.5.6; TASK-299).
    ///
    /// The Boss-side counterpart of <see cref="ApplyDefenseBuff(Battle.PetState, int)"/>:
    /// same identity, same refresh-not-stack rule, same zero-pool rule, and the
    /// Boss's own collection as the carrier (<c>ADR-026</c> item 4). The one
    /// difference is the applied duration — the Boss row of §5.4.6's window
    /// table, <see cref="BossDefBuffDurationTurns"/> — because the Boss's buff is
    /// applied at step 18a, after the Player's attack phase of that Turn, and must
    /// remain active through the Player's step-15 attack of the following Turn.
    /// </summary>
    /// <param name="previous">The Boss's state before this DEF buff.</param>
    /// <param name="defensePool">This action's generated Defense.</param>
    /// <returns><paramref name="previous"/> with the buff applied or refreshed.</returns>
    public static Battle.BossState ApplyDefenseBuff(
        Battle.BossState previous,
        int defensePool)
    {
        if (defensePool <= 0)
        {
            return previous;
        }

        var buff = Battle.StatusEffect.TurnBased(
            Battle.StatusEffectLifecycle.DefenseBuffId,
            Battle.StatusEffectType.BuffDebuff,
            Battle.StatusEffectSource.Boss,
            defensePool,
            BossDefBuffDurationTurns,
            Battle.StatusEffectLifecycle.DefenseStat);

        return previous with
        {
            ActiveStatusEffects = Battle.StatusEffectLifecycle.Apply(previous.ActiveStatusEffects, buff),
        };
    }

    public static Battle.BossState ApplyDefenseBuff(
        Battle.BossState previous,
        ResourceGeneration generation) =>
        ApplyDefenseBuff(previous, generation.DefensePool);

    /// <summary>
    /// Applies actor-relative match effects (DEF buff, HP Heal, POWER) according to the acting actor
    /// (<c>ADR-026</c> Scope B, Scope E; <c>COMBAT_RULES.md</c> §2, §5.4.6, §5.5.6).
    ///
    /// <b>DEF Gems grant the acting actor's DEF buff, not a Shield (TASK-299).</b>
    /// The acting side owns every effect it generates (<c>ADR-026</c> item 4): a
    /// Player action applies the buff to the Pet with
    /// <see cref="PlayerDefBuffDurationTurns"/>, a Boss action applies it to the
    /// Boss with <see cref="BossDefBuffDurationTurns"/>. The two calls can never
    /// cross entities, and no Shield instance is created on either path.
    ///
    /// <b>POWER Gems generate Power, and only Power (ADR-029 Slice 5 / TASK-313).</b>
    /// The Player branch writes <c>PetState.Power</c>; the Boss branch writes
    /// <c>BossState.Power</c> through the same shared rule
    /// (<c>COMBAT_RULES.md</c> §2, <c>ADR-029</c> §2.2). The retired
    /// <c>BossState.SkillCharge</c> accumulator is gone: this method performs no
    /// charge write-back and takes no charge-requirement argument.
    /// </summary>
    public static (Battle.PetState Pet, Battle.BossState Boss) ApplyActorMatchEffects(
        Combat.DamageParty actingParty,
        Battle.PetState petState,
        Battle.BossState bossState,
        ResourceGeneration generation,
        CascadeResolver.CascadeResult resolution)
    {
        if (actingParty == Combat.DamageParty.Player)
        {
            var updatedPet = ApplyHeal(petState, generation, bossState.ActiveStatusEffects);
            updatedPet = ApplyDefenseBuff(updatedPet, generation);
            updatedPet = ApplyPower(updatedPet, generation);
            return (updatedPet, bossState);
        }
        else
        {
            var updatedBoss = ApplyBossHeal(bossState, generation);
            updatedBoss = ApplyDefenseBuff(updatedBoss, generation);
            updatedBoss = ApplyBossPower(updatedBoss, generation);
            return (petState, updatedBoss);
        }
    }
